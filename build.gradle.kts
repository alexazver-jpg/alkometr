// Корневой build-скрипт проекта. Gradle читает его раньше build-файлов модулей
// и выполняет один раз для всей сборки, поэтому здесь только общие объявления.
//
// Про Gradle wrapper. В проекте есть папка gradle/wrapper (файл gradle-wrapper.properties)
// и скрипты gradlew / gradlew.bat. Wrapper — это «закреплённая» версия Gradle: скрипт сам
// скачивает нужный дистрибутив и запускает именно его. Поэтому сборка не зависит от того,
// какой Gradle установлен в системе, и у всех разработчиков и на CI получается одинаковый результат.
// Запускать сборку принято через ./gradlew (Windows: gradlew.bat), а не через системный gradle.

plugins { // Блок «plugins» объявляет Gradle-плагины. Плагин — это расширение Gradle:
    // он добавляет в сборку новые задачи (task) и новые блоки настроек (DSL).
    // Например, Android-плагин добавляет блок android {} и задачи сборки APK.

    // alias(...) берёт плагин из каталога версий gradle/libs.versions.toml, поэтому
    // версия хранится в одном месте и не дублируется по модулям.
    // apply false означает «объявить плагин и загрузить его, но не применять к этому проекту»:
    // у корня нет Android-кода, так что AGP (Android Gradle Plugin) включится только в модуле app.
    alias(libs.plugins.android.application) apply false
}
