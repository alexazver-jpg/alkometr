package ru.alkometr.app.core.model

// Импорт плагина сериализации: пресеты сохраняются в настройках как список JSON-объектов.
import kotlinx.serialization.Serializable

/**
 * Пресет напитка для кнопки на главном экране.
 * Название не хранится: подпись собирается из вида сосуда, объёма и крепости.
 *
 * @param id стабильный идентификатор пресета: по нему пресет находят после сохранения.
 * @param kind вид сосуда — даёт иконку и подпись по умолчанию.
 * @param volumeMl объём порции, миллилитры.
 * @param abvPercent крепость, объёмные проценты (40.0 — это 40 % об.).
 * @param name своё название; `String?` и значение по умолчанию null — имя можно не задавать.
 */
@Serializable
data class DrinkPreset(
    val id: String,  // ключ пресета, например "preset_shot"
    val kind: DrinkKind,  // вид сосуда: иконка и текст на кнопке
    val volumeMl: Double,  // объём: подставляется в новую порцию одним нажатием
    val abvPercent: Double,  // крепость: тоже подставляется в порцию
    /** Необязательное своё название; если пусто — на кнопке показывается вид сосуда. */
    val name: String? = null,  // null означает «показывать подпись по виду сосуда»
) {
    // Компаньон-объект: набор пресетов «из коробки».
    companion object {
        /** Стандартный набор кнопок: рюмка водки, бокал вина, кружка пива. */
        fun defaults(): List<DrinkPreset> = listOf(
            // 50 мл × 40 % × 0,789 ≈ 15,8 г чистого этанола — классическая «стопка».
            DrinkPreset("preset_shot", DrinkKind.SHOT, 50.0, 40.0),
            // 150 мл × 12 % × 0,789 ≈ 14,2 г — примерно та же доза, что и в рюмке водки.
            DrinkPreset("preset_wine", DrinkKind.WINE_GLASS, 150.0, 12.0),
            // 500 мл × 5 % × 0,789 ≈ 19,7 г — «поллитра пива» крепостью 5 %.
            DrinkPreset("preset_mug", DrinkKind.MUG, 500.0, 5.0),
        )
    }
}

/**
 * Пресеты юридического порога для вождения, ‰ (г/л).
 *
 * Значения — ориентиры по законодательству разных стран; в настройках порог
 * можно задать и вручную, эти пресеты лишь заполняют поле одним нажатием.
 *
 * @param permille значение порога в промилле; оно же равно г/л.
 */
enum class ThresholdPreset(val permille: Double) {
    // Россия: 0,3 ‰ в крови (0,16 мг/л в выдохе) — с учётом допустимой погрешности прибора.
    RUSSIA(0.3),
    // Большинство стран Европы: 0,5 ‰.
    EUROPE(0.5),
    // США: 0,8 ‰ (для водителей старше 21 года).
    USA(0.8),
    // Полный запрет: превышать нельзя даже на 0,0 ‰.
    ZERO(0.0),
}