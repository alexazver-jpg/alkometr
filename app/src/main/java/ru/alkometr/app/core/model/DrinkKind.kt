package ru.alkometr.app.core.model

// Импорт плагина сериализации: вид сосуда сохраняется в JSON как обычная строка.
import kotlinx.serialization.Serializable

/**
 * Вид сосуда. Влияет только на иконку и подпись, на расчёт — нет.
 *
 * `enum class` — перечисление: фиксированный набор именованных значений. Компилятор не даст
 * передать сюда ничего постороннего, а когда-нибудь `when` по нему проверит полноту веток.
 */
@Serializable
enum class DrinkKind {
    // Рюмка/шот: маленький объём, высокая крепость (водка, коньяк, ликёр).
    SHOT,
    // Бокал вина: средний объём, средняя крепость.
    WINE_GLASS,
    // Кружка: большой объём, слабая крепость (пиво, сидр).
    MUG,
    // Своя порция: объём и крепость вводит пользователь вручную.
    CUSTOM,
}
