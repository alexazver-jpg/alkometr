package ru.alkometr.app.core.model

// Импорт плагина сериализации: выбранный пол сохраняется в настройках как строка "MALE"/"FEMALE"/...
import kotlinx.serialization.Serializable

/**
 * Пол определяет коэффициент распределения r в формуле Видмарка.
 *
 * Формула Видмарка: C = D / (r · m), где C — концентрация (г/л), D — доза чистого спирта (г),
 * m — масса тела (кг), r — доля воды в теле. Алкоголь растворяется именно в воде, поэтому
 * у мужчин (воды около 0,71 от массы) концентрация при той же дозе ниже, чем у женщин (0,58).
 */
@Serializable
enum class Sex(val r: Double) {
    // Мужской: r = 0,71 — алкоголь «разбавляется» большим объёмом воды в организме.
    MALE(0.71),
    // Женский: r = 0,58 — при той же дозе концентрация в крови примерно на 20 % выше.
    FEMALE(0.58),
    // Не указан: среднее значение — компромисс, когда пользователь не хочет уточнять.
    UNSPECIFIED(0.65),
}