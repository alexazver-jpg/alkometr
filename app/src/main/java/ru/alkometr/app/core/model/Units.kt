package ru.alkometr.app.core.model

// Импорт плагина сериализации: выбранные единицы сохраняются в настройках как строка.
import kotlinx.serialization.Serializable

/**
 * Единицы отображения концентрации. Внутри всё считается в г/л (это же и промилле).
 *
 * ‰         — 1 г/л = 1 ‰;
 * % BAC     — объёмные проценты: 1 г/л = 0,1 %;
 * мг/100 мл — 1 г/л = 100 мг/100 мл;
 * мг/л      — концентрация в крови: 1 г/л = 1000 мг/л.
 *
 * Единая внутренняя единица (г/л) — важное решение: все расчёты идут в ней, а перевод
 * делается только при показе и вводе. Иначе пришлось бы согласовывать единицы в каждой формуле.
 *
 * @param symbol подпись единицы для интерфейса.
 * @param factorFromGramPerLiter во сколько раз значение в этих единицах больше, чем в г/л.
 * @param decimals сколько знаков после запятой показывать.
 */
@Serializable
enum class Units(
    val symbol: String,  // то, что видит пользователь рядом с числом
    val factorFromGramPerLiter: Double,  // множитель перевода из г/л в эти единицы
    val decimals: Int,  // точность отображения: 2 знака для ‰ и %, 0 — для миллиграммов
) {
    // Промилле: 1 г/л = 1 ‰, поэтому коэффициент 1,0; два знака — 0,35 ‰.
    PERMILLE("‰", 1.0, 2),
    // Объёмные проценты (как в США): 1 г/л = 0,1 %, поэтому коэффициент 0,1.
    PERCENT("%", 0.1, 2),
    // Миллиграммы на 100 мл (медицинские анализаторы): 1 г/л = 100 мг/100 мл.
    MG_PER_100ML("мг/100 мл", 100.0, 0),
    // Миллиграммы на литр: 1 г/л = 1000 мг/л; целые числа, дробная часть не нужна.
    MG_PER_LITER("мг/л", 1000.0, 0);

    /**
     * Переводит значение из г/л в выбранные единицы.
     *
     * @param bacGPerL концентрация в г/л.
     */
    fun fromBac(bacGPerL: Double): Double = bacGPerL * factorFromGramPerLiter

    /**
     * Обратный перевод: значение в этих единицах → г/л.
     * Нужен, когда пользователь вводит порог в выбранных единицах.
     */
    fun toBac(value: Double): Double = value / factorFromGramPerLiter

    // Компаньон-объект: значения по умолчанию для настроек.
    companion object {
        /** Порог по умолчанию — Россия, 0,3 ‰. */
        // 0,3 ‰ в крови ≈ 0,16 мг/л в выдохе — это допустимая погрешность измерения, а не «норма».
        const val DEFAULT_THRESHOLD_PERMILLE = 0.3
    }
}