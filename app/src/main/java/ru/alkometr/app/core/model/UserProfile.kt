package ru.alkometr.app.core.model

// Импорт плагина сериализации: профиль целиком сохраняется в настройки как JSON.
import kotlinx.serialization.Serializable

/**
 * Профиль пользователя. Обязательны только вес и пол,
 * остальное — необязательные уточнения.
 *
 * Значения по умолчанию прямо в конструкторе (`= 80.0`) позволяют создать объект без аргументов:
 * `UserProfile()` — это валидный профиль «среднего человека», с которого можно начать.
 *
 * @param weightKg масса тела, кг. Входит в объём распределения: Vd = r · m.
 * @param sex пол — задаёт коэффициент r в формуле Видмарка.
 * @param heightCm рост, см; необязательное уточнение (null — пользователь не указал).
 * @param ageYears возраст, лет; необязательное уточнение (null — не указан).
 */
@Serializable
data class UserProfile(
    val weightKg: Double = 80.0,  // вес: главный параметр, чем больше масса, тем ниже концентрация
    val sex: Sex = Sex.UNSPECIFIED,  // пол: подставляет r = 0,65, если ничего не выбрано
    val heightCm: Int? = null,  // `Int?` — тип «целое или null»: отсутствие значения допустимо
    val ageYears: Int? = null,  // возраст тоже необязателен: на модель напрямую не влияет
) {
    // Компаньон-объект: границы допустимых значений для валидации ввода в UI.
    companion object {
        // Допустимый вес, кг: ниже 30 или выше 200 — почти наверняка опечатка при вводе.
        // `..` создаёт диапазон (ClosedFloatingPointRange), проверка: weightKg in WEIGHT_RANGE.
        val WEIGHT_RANGE = 30.0..200.0
        // Рост, см: 120..220 — реалистичные границы для взрослого человека.
        val HEIGHT_RANGE = 120..220
        // Возраст, лет: 18..100 — приложение только для совершеннолетних.
        val AGE_RANGE = 18..100
    }
}