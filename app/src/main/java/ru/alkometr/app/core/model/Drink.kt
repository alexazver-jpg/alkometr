package ru.alkometr.app.core.model

// Импорт плагина сериализации: аннотация @Serializable учит kotlinx.serialization превращать объект в JSON.
import kotlinx.serialization.Serializable

/**
 * Одна выпитая порция. Время хранится в epoch-миллисекундах UTC,
 * отображение — всегда в локальном часовом поясе.
 *
 * Почему UTC: абсолютный момент времени не зависит от часового пояса и перевода часов,
 * а показать «в 20:30 по местному» можно уже на слое UI.
 *
 * @param id уникальный идентификатор порции (например, UUID) — нужен, чтобы удалить или изменить запись.
 * @param atMillis когда выпито, миллисекунды от 01.01.1970 UTC.
 * @param volumeMl объём порции, миллилитры.
 * @param abvPercent крепость в объёмных процентах: 40.0 — это 40 % об. (водка), 5.0 — пиво.
 * @param kind вид сосуда: только иконка и подпись, на расчёт не влияет.
 */
@Serializable
data class Drink(
    val id: String,  // строка-идентификатор: по ней ищут запись в списке и в базе
    val atMillis: Long,  // время употребления: сдвигает момент «включения» дозы в модели
    val volumeMl: Double,  // объём: вместе с крепостью даёт граммы этанола
    val abvPercent: Double,  // крепость: доля спирта по объёму, в процентах
    val kind: DrinkKind,  // вид сосуда: чисто оформительская информация
) {
    /**
     * Масса чистого этанола в порции, граммы.
     *
     * Формула: объём (мл) × доля спирта × плотность этанола (0,789 г/мл).
     * Пример: 50 мл водки 40 % → 50 × 0,40 × 0,789 ≈ 15,8 г чистого спирта.
     * Именно граммы нужны модели: доза D в уравнении всасывания измеряется в граммах,
     * а не в миллилитрах, потому что крепость у напитков разная.
     */
    val ethanolGrams: Double
        // `get()` без поля: значение вычисляется при каждом обращении, отдельная ячейка памяти не нужна.
        get() = volumeMl * (abvPercent / 100.0) * ETHANOL_DENSITY

    // Компаньон-объект: константы, общие для всех экземпляров Drink.
    companion object {
        /** Плотность этанола, г/мл. */
        // 0,789 г/мл при 20 °C: спирт легче воды (у воды 1,0 г/мл), поэтому 100 мл спирта — это 78,9 г.
        const val ETHANOL_DENSITY = 0.789
    }
}
