package ru.alkometr.app.core.model

// Импорт плагина сериализации: параметры и переопределения сохраняются в JSON.
import kotlinx.serialization.Serializable

/**
 * Насколько плотно человек поел перед первой порцией — влияет на скорость всасывания.
 *
 * ka, 1/час — константа скорости всасывания из желудка в кровь. Пустой желудок: всасывание
 * быстрое (2,0), плотная еда замедляет его (0,8), поэтому пик получается ниже и позже.
 */
@Serializable
enum class FoodIntake(val kaPerHour: Double) {
    // Пустой желудок: алкоголь быстро уходит в кровь, пик выше и раньше.
    EMPTY_STOMACH(2.0),
    // Обычный приём пищи — базовый вариант для большинства расчётов.
    NORMAL(1.5),
    // Плотная, особенно жирная еда: всасывание медленнее, «накрывает» позже и плавнее.
    HEAVY(0.8),
}

/**
 * Привычная частота употребления — влияет на скорость выведения.
 *
 * Vmax, г/(л·ч) — максимальная скорость работы ферментов печени (алкогольдегидрогеназы).
 * У регулярно пьющих она выше: печень адаптируется. Значения ориентировочные: модель
 * не претендует на медицинскую точность, это оценка «на глаз».
 */
@Serializable
enum class Metabolism(val vmaxGPerLH: Double) {
    // Медленный обмен: около 0,12 ‰ в час, то есть примерно 0,12 г/л за час.
    SLOW(0.12),
    // Средний, самый частый вариант: около 0,15 ‰ в час.
    AVERAGE(0.15),
    // Быстрый: около 0,18 ‰ в час.
    FAST(0.18),
}

/**
 * Параметры модели для конкретного расчёта.
 * Значения по умолчанию — физиологически обоснованные средние, не подогнанные под тесты.
 *
 * @param weightKg масса тела, кг.
 * @param r доля воды в теле (коэффициент Видмарка), безразмерный: 0,58…0,71.
 * @param kaPerHour константа всасывания, 1/час.
 * @param vmaxGPerLH максимальная скорость выведения, г/(л·ч).
 * @param kmGPerL константа Михаэлиса, г/л: при такой концентрации скорость выведения равна Vmax/2.
 */
data class ModelParams(
    val weightKg: Double,  // масса тела, кг: входит в объём распределения
    val r: Double,  // доля воды в теле: определяется полом (Sex.r)
    val kaPerHour: Double,  // скорость всасывания, 1/час: определяется сытостью (FoodIntake)
    val vmaxGPerLH: Double,  // потолок скорости выведения, г/(л·ч): определяется метаболизмом
    val kmGPerL: Double = KM_DEFAULT,  // константа Михаэлиса; по умолчанию 0,02 г/л
) {
    /**
     * Объём распределения, литры.
     *
     * Физика: алкоголь распределяется по воде тела, и её объём примерно равен r · m.
     * 1 кг воды ≈ 1 литр, поэтому численно литры совпадают с килограммами.
     * Чем больше Vd, тем сильнее «разбавлена» доза и тем ниже концентрация.
     */
    val vdLiters: Double
        // Свойство-вычисление: Vd = r · масса тела.
        get() = r * weightKg

    // Компаньон-объект: константы модели и фабрика параметров.
    companion object {
        // Km по умолчанию, г/л. Малое значение означает, что уже при небольших концентрациях
        // ферменты почти насыщены, и выведение идёт почти с постоянной скоростью Vmax.
        const val KM_DEFAULT = 0.02
        // Vmax по умолчанию, г/(л·ч) — средняя скорость выведения, около 0,15 ‰ в час.
        const val VMAX_DEFAULT = 0.15
        // ka по умолчанию, 1/час — соответствует обычному приёму пищи (FoodIntake.NORMAL).
        const val KA_DEFAULT = 1.5

        /**
         * Собирает параметры из профиля, характера еды и метаболизма.
         *
         * Это удобная «точка сборки»: экран настроек передаёт три простых выбора,
         * а модель получает уже готовые числа для расчёта.
         *
         * @param profile профиль пользователя — даёт вес и коэффициент r.
         * @param food сытость — даёт ka.
         * @param metabolism метаболизм — даёт Vmax.
         */
        fun of(
            profile: UserProfile,
            food: FoodIntake = FoodIntake.NORMAL,
            metabolism: Metabolism = Metabolism.AVERAGE,
        ): ModelParams = ModelParams(
            weightKg = profile.weightKg,  // вес берём из профиля как есть
            r = profile.sex.r,  // коэффициент Видмарка подставляет сам пол
            kaPerHour = food.kaPerHour,  // скорость всасывания — из выбранной сытости
            vmaxGPerLH = metabolism.vmaxGPerLH,  // скорость выведения — из метаболизма
            kmGPerL = KM_DEFAULT,  // Km всегда рекомендуемое: у пользователя нет причин его менять
        )
    }
}

/**
 * Ручные переопределения параметров модели из настроек.
 * null — использовать рекомендуемое значение.
 *
 * Смысл: большинству пользователей хватает готовых значений, но «продвинутый» режим
 * позволяет ввести свои числа. null здесь — это «не задано», а не «ноль».
 *
 * @param kaPerHour своё значение ka, 1/час (null — брать из FoodIntake).
 * @param vmaxGPerLH своё значение Vmax, г/(л·ч) (null — брать из Metabolism).
 * @param kmGPerL своё значение Km, г/л (null — KM_DEFAULT).
 * @param r своё значение коэффициента Видмарка (null — брать из пола).
 */
@Serializable
data class ModelOverrides(
    val kaPerHour: Double? = null,  // null по умолчанию: ничего не переопределено
    val vmaxGPerLH: Double? = null,  // аналогично для скорости выведения
    val kmGPerL: Double? = null,  // аналогично для константы Михаэлиса
    val r: Double? = null,  // аналогично для доли воды в теле
) {
    /** Все ли переопределения пусты, то есть пользователь ничего не менял вручную. */
    val isEmpty: Boolean
        // `&&` — логическое «И»: истина только если каждое поле равно null.
        get() = kaPerHour == null && vmaxGPerLH == null && kmGPerL == null && r == null

    /**
     * Накладывает заданные вручную значения на базовые параметры.
     *
     * `copy(...)` — метод data-класса: создаёт копию объекта с изменёнными полями,
     * исходный объект при этом остаётся неизменным.
     */
    fun applyTo(base: ModelParams): ModelParams = base.copy(
        // Elvis-оператор `?:`: если переопределение задано — берём его, иначе значение из base.
        kaPerHour = kaPerHour ?: base.kaPerHour,
        vmaxGPerLH = vmaxGPerLH ?: base.vmaxGPerLH,
        kmGPerL = kmGPerL ?: base.kmGPerL,
        r = r ?: base.r,
    )
}
