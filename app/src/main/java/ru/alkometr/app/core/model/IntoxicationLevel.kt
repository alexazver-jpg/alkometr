package ru.alkometr.app.core.model

/**
 * Пять степеней опьянения. Границы — константы в одном месте.
 *
 * Важно: степень опьянения и юридический порог для вождения — разные вещи.
 * Статус «можно за руль» считается по порогу из настроек, а не по номеру степени.
 *
 * Поля элемента перечисления:
 *  - minBac — нижняя граница степени в ‰ (она же г/л);
 *  - titleKey — ключ строкового ресурса для локализации, сам текст лежит в strings.xml;
 *  - colorArgb — цвет индикатора в формате ARGB: 0xFF... означает полностью непрозрачный цвет;
 *  - iconKey — имя ресурса иконки для этой степени.
 */
enum class IntoxicationLevel(
    val minBac: Double,  // с какого значения начинается эта степень, ‰
    val titleKey: String,  // ключ локализации, а не готовый текст
    val colorArgb: Long,  // цвет для шкалы и карточки: тип Long, потому что ARGB — 32 бита
    val iconKey: String,  // имя drawable-ресурса с иконкой степени
) {
    // Трезв: от 0,00 ‰; тёмно-зелёный цвет — «всё в порядке».
    SOBER(0.0, "sober", 0xFF2E7D32, "ic_level_1"),
    // Лёгкое опьянение: от 0,20 ‰; салатовый.
    MILD(0.20, "mild", 0xFF9CCC65, "ic_level_2"),
    // Средняя степень: от 0,50 ‰; жёлтый.
    MODERATE(0.50, "moderate", 0xFFFBC02D, "ic_level_3"),
    // Сильное опьянение: от 1,50 ‰; оранжевый.
    STRONG(1.50, "strong", 0xFFEF6C00, "ic_level_4"),
    // Опасная для жизни концентрация: от 2,50 ‰; красный.
    // Точка с запятой в конце нужна, потому что после констант начинаются члены класса.
    DANGEROUS(2.50, "dangerous", 0xFFC62828, "ic_level_5");

    /** Верхняя граница диапазона (исключительно); у последней степени — бесконечность. */
    val maxBac: Double
        // `when (this)` — разбор по значению перечисления: ветки должны покрывать все элементы.
        get() = when (this) {
            // Верхняя граница степени — это нижняя граница следующей, поэтому границы не дублируются.
            SOBER -> MILD.minBac
            // Для каждой следующей степени — та же логика: конец = начало следующей.
            MILD -> MODERATE.minBac
            // Средняя степень заканчивается там, где начинается сильная.
            MODERATE -> STRONG.minBac
            // Сильная — там, где начинается опасная.
            STRONG -> DANGEROUS.minBac
            // У последней степени верхней границы нет: бесконечность.
            DANGEROUS -> Double.POSITIVE_INFINITY
        }

    // Компаньон-объект: общая константа шкалы и функция выбора степени по значению.
    companion object {
        /** Верхняя граница шкалы-индикатора, ‰. */
        // 4,0 ‰ — уже смертельно опасно, дальше шкалу растягивать незачем.
        const val SCALE_MAX = 4.0

        /**
         * Степень для заданной концентрации: берём последнюю, чья нижняя граница не выше значения.
         *
         * @param bac концентрация в г/л (‰).
         */
        fun forBac(bac: Double): IntoxicationLevel {
            // NaN («не число», например 0.0/0.0) не сравним ни с чем — трактуем как трезвость,
            // чтобы UI не падал на некорректном входном значении.
            val value = if (bac.isNaN()) 0.0 else bac
            // `entries` — все элементы перечисления в порядке объявления;
            // `last { ... }` — последний подходящий, то есть самая высокая достигнутая степень.
            return entries.last { value >= it.minBac }
        }
    }
}
