package ru.alkometr.app.data

import kotlinx.serialization.json.Json
import ru.alkometr.app.core.model.AppSettings
import ru.alkometr.app.core.model.Drink
import kotlinx.serialization.Serializable

// @Serializable — не «магия рантайма»: плагин kotlinx.serialization на этапе компиляции
// генерирует для класса код, который умеет превращать объект в JSON и обратно.
// Поэтому здесь нет ручного разбора полей и легко заметить расхождение форматов.
/** Формат файла резервной копии. */
@Serializable
data class Backup(
    // Имя формата: при импорте проверяем его, чтобы не принять за копию произвольный JSON.
    val format: String = FORMAT,
    // Версия схемы файла: позволяет отличить старую копию от новой и отказаться от будущей.
    val version: Int = VERSION,
    // Момент экспорта в миллисекундах: нужен пользователю как подпись «когда сделана копия».
    val exportedAtMillis: Long,
    // Настройки целиком: сериализуются вложенным JSON-объектом, а не набором отдельных ключей.
    val settings: AppSettings,
    // Порции истории: массив объектов, порядок в файле не важен, важен atMillis у каждой.
    val drinks: List<Drink>,
) {
    // companion object — константы формата: снаружи доступны как Backup.FORMAT и Backup.VERSION.
    companion object {
        // Строка-маркер в JSON. Если её нет, файл точно не наш — понятная ошибка вместо мусора.
        const val FORMAT = "alkometr-backup"
        // Текущая версия схемы. Увеличиваем, когда меняем структуру файла несовместимо.
        const val VERSION = 1
    }
}

/** Экспорт и импорт данных приложения в JSON. */
object BackupCodec {

    // Json — настроенный «сериализатор». Создаётся один раз, потому что настройки неизменны.
    private val json = Json {
        // Отступы и переводы строк: файл должен читаться глазами и нормально смотреться в diff.
        prettyPrint = true
        // Писать в JSON даже значения по умолчанию: файл получается самодостаточным,
        // и импорт в другой версии приложения не зависит от совпадения дефолтов.
        encodeDefaults = true
        // Неизвестные ключи при чтении игнорируем: копия из более новой версии не должна
        // падать целиком из-за одного нового поля, которое эта версия ещё не знает.
        ignoreUnknownKeys = true
    }

    // encode — чистая функция: получает данные и возвращает строку, ничего не пишет на диск.
    // Куда сохранить файл, решает вызывающий код, поэтому кодек можно тестировать без Android.
    fun encode(settings: AppSettings, drinks: List<Drink>, exportedAtMillis: Long): String =
        // encodeToString(serializer, value) — явно передаём сериализатор: так компилятор
        // не ищет его неявно и код одинаково работает в любом месте проекта.
        json.encodeToString(
            // Сериализатор сгенерирован плагином и лежит в companion object класса Backup.
            Backup.serializer(),
            Backup(
                // Время экспорта подставляет вызывающая сторона — так функцию легко проверить в тесте.
                exportedAtMillis = exportedAtMillis,
                settings = settings,
                // Сортируем по времени: одинаковый набор данных всегда даёт одинаковый файл,
                // и в системе контроля версий видно только реальные изменения.
                drinks = drinks.sortedBy { it.atMillis },
            ),
        )

    /**
     * Разбор резервной копии. Бросает [IllegalArgumentException] с понятным текстом,
     * если файл не от этого приложения или повреждён.
     */
    fun decode(text: String): Backup {
        // Ошибки разбора (битый JSON, не тот тип поля, отсутствует обязательный ключ)
        // ловим все сразу: пользователю не важно, что именно сломалось, важно — что файл не подошёл.
        val backup = try {
            // Обратная операция: строка -> объект Backup.
            json.decodeFromString(Backup.serializer(), text)
        } catch (e: Exception) {
            // Оборачиваем исходное исключение в понятное сообщение и не теряем причину (e).
            throw IllegalArgumentException("Файл не является резервной копией «АлкоМетра»", e)
        }
        // require проверяет условие и бросает IllegalArgumentException с нашим текстом.
        // Сначала маркер формата: чужой JSON отсекаем до любых дальнейших проверок.
        require(backup.format == Backup.FORMAT) { "Неизвестный формат файла: ${backup.format}" }
        // Версия не должна быть новее нашей: иначе в файле могут быть поля, которых мы не знаем,
        // и импорт молча потеряет данные. Лучше честно отказаться.
        require(backup.version <= Backup.VERSION) { "Файл создан более новой версией приложения" }
        // Проверки пройдены — отдаём разобранный объект вызывающему коду.
        return backup
    }
}
